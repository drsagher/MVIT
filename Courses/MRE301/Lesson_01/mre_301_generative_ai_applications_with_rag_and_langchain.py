"""**Build a simple multi-format loader**"""

from pathlib import Path

LOADERS = {
    ".txt":  TextLoader,
    ".pdf":  PyMuPDFLoader,
    ".md":   UnstructuredMarkdownLoader,
    ".csv":  CSVLoader,
    ".docx": Docx2txtLoader,
    ".xlsx": UnstructuredExcelLoader,
    ".pptx": UnstructuredPowerPointLoader,
}

def load_any(path):
    ext = Path(path).suffix.lower()
    loader_cls = LOADERS.get(ext, UnstructuredFileLoader)   # fallback
    return loader_cls(str(path)).load()

# Ensure the directories exist
client_files_dir = Path("client_files")
client_files_dir.mkdir(exist_ok=True)
sample_data_dir = Path("sample_data")

docs = []

# Load files from client_files directory
for file in client_files_dir.iterdir():
    if file.is_file():
        try:
            docs.extend(load_any(file))
        except Exception as e:
            print(f"Could not load {file.name}: {e}")

# Load files from sample_data directory
if sample_data_dir.exists():
    for file in sample_data_dir.iterdir():
        if file.is_file():
            try:
                docs.extend(load_any(file))
            except Exception as e:
                print(f"Could not load {file.name}: {e}")

print(f"Loaded {len(docs)} documents")